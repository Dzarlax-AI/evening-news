// This fixture uses a unique schema on an explicitly loopback-only PostgreSQL
// URL. The HTTP handlers use real Go repositories and the assertions query
// the persisted rows instead of inspecting an in-memory stub.
type legacyContractDB struct {
	admin  *pgxpool.Pool
	pool   *pgxpool.Pool
	reader *repositories.Postgres
	schema string
}

func newLegacyContractDB(t *testing.T) *legacyContractDB {
	t.Helper()
	dsn := os.Getenv("TEST_DATABASE_URL")
	if dsn == "" {
		t.Skip("TEST_DATABASE_URL is required for loopback PostgreSQL legacy-contract tests")
	}
	parsed, err := url.Parse(dsn)
	if err != nil {
		t.Fatal(err)
	}
	if host := parsed.Hostname(); host != "127.0.0.1" && host != "localhost" && (net.ParseIP(host) == nil || !net.ParseIP(host).IsLoopback()) {
		t.Fatalf("refusing non-loopback TEST_DATABASE_URL host %q", host)
	}
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	cfg, err := pgxpool.ParseConfig(dsn)
	if err != nil {
		t.Fatal(err)
	}
	admin, err := pgxpool.NewWithConfig(ctx, cfg)
	if err != nil {
		t.Fatal(err)
	}
	schema := fmt.Sprintf("legacy_contract_%d", time.Now().UnixNano())
	if _, err = admin.Exec(ctx, "CREATE SCHEMA "+schema); err != nil {
		admin.Close()
		t.Fatal(err)
	}
	appCfg, err := pgxpool.ParseConfig(dsn)
	if err != nil {
		admin.Close()
		t.Fatal(err)
	}
	appCfg.ConnConfig.RuntimeParams["search_path"] = schema
	pool, err := pgxpool.NewWithConfig(ctx, appCfg)
	if err != nil {
		_, _ = admin.Exec(ctx, "DROP SCHEMA "+schema+" CASCADE")
		admin.Close()
		t.Fatal(err)
	}
	publicURL := *parsed
	query := publicURL.Query()
	query.Set("search_path", schema)
	publicURL.RawQuery = query.Encode()
	reader, err := repositories.OpenPostgres(ctx, publicURL.String(), 4)
	if err != nil {
		pool.Close()
		_, _ = admin.Exec(ctx, "DROP SCHEMA "+schema+" CASCADE")
		admin.Close()
		t.Fatal(err)
	}
	fixture := &legacyContractDB{admin: admin, pool: pool, reader: reader, schema: schema}
	t.Cleanup(func() {
		reader.Close()
		pool.Close()
		_, _ = admin.Exec(context.Background(), "DROP SCHEMA "+schema+" CASCADE")
		admin.Close()
	})
	for _, statement := range legacyContractDDL(schema) {
		if _, err = admin.Exec(ctx, statement); err != nil {
			t.Fatalf("create fixture schema: %v\n%s", err, statement)
		}
	}
	return fixture
}

func legacyContractDDL(schema string) []string {
	return []string{
		`CREATE TABLE ` + schema + `.sources(id bigint PRIMARY KEY,name text NOT NULL,source_type text NOT NULL,url text NOT NULL,enabled boolean NOT NULL DEFAULT true)`,
		`CREATE TABLE ` + schema + `.categories(id bigint PRIMARY KEY,name text NOT NULL,display_name text NOT NULL,color text NOT NULL)`,
		`CREATE TABLE ` + schema + `.articles(id bigint PRIMARY KEY,source_id bigint REFERENCES ` + schema + `.sources(id),title text NOT NULL,summary text,content text,url text NOT NULL,image_url text,media_files jsonb,published_at timestamp,fetched_at timestamp,is_advertisement boolean,ad_confidence real,ad_type text,ad_reasoning text,ad_markers jsonb,processing_state text,ad_processed boolean)`,
		`CREATE TABLE ` + schema + `.article_categories(id bigint PRIMARY KEY,article_id bigint NOT NULL,category_id bigint NOT NULL,confidence real,ai_category text)`,
		`CREATE TABLE ` + schema + `.daily_summaries(id bigint PRIMARY KEY,date date NOT NULL,category text NOT NULL,summary_text text NOT NULL,articles_count integer NOT NULL)`,
		`CREATE TABLE ` + schema + `.background_jobs(id uuid PRIMARY KEY,queue_position bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE NOT NULL,kind varchar(40) NOT NULL,payload jsonb NOT NULL,idempotency_key varchar(200) UNIQUE NOT NULL,coalesce_key varchar(64),state varchar(24) NOT NULL DEFAULT 'queued',created_at timestamp NOT NULL DEFAULT (timezone('UTC',now())),started_at timestamp,finished_at timestamp,owner_generation integer,attempt_generation integer NOT NULL DEFAULT 0,initialized_at timestamp,schedule_key varchar(128),schedule_revision integer,occurrence_id uuid,scheduled_for timestamp,result jsonb,error_code varchar(40))`,
		`CREATE UNIQUE INDEX background_jobs_active_coalesce ON ` + schema + `.background_jobs(coalesce_key) WHERE state IN ('queued','running','interrupted') AND coalesce_key IS NOT NULL`,
		`CREATE TABLE ` + schema + `.background_job_idempotency_keys(key varchar(200) PRIMARY KEY,job_id uuid NOT NULL REFERENCES ` + schema + `.background_jobs(id) ON DELETE CASCADE,created_at timestamp NOT NULL DEFAULT (timezone('UTC',now())))`,
		`CREATE TABLE ` + schema + `.background_worker_status(id integer PRIMARY KEY,generation bigint NOT NULL DEFAULT 0,owner_id uuid,heartbeat_at timestamp,status varchar(16) NOT NULL DEFAULT 'stopped')`,
		`CREATE TABLE ` + schema + `.scheduler_occurrence_receipts(occurrence_id uuid PRIMARY KEY,envelope_sha256 varchar(64) NOT NULL,job_id uuid NOT NULL,accepted_at timestamp NOT NULL DEFAULT (timezone('UTC',now())))`,
		`INSERT INTO ` + schema + `.background_worker_status(id,generation,status,heartbeat_at) VALUES(1,1,'running',timezone('UTC',now()))`,
	}
}

func legacyAdminHTTP(t *testing.T, db *legacyContractDB) (*http.ServeMux, string) {
	t.Helper()
	service := auth.New(auth.Config{Username: "fixture-admin", Password: "fixture-password", JWTSecret: "fixture-signing-key"})
	token, err := service.Mint("fixture-admin", auth.LevelAdmin)
	if err != nil {
		t.Fatal(err)
	}
	jobService := jobs.New(repositories.NewJobRepository(db.pool))
	managementService := management.New(repositories.NewManagementRepository(db.pool), jobService, nil)
	mux := http.NewServeMux()
	h := New(Config{Reader: db.reader, PublicAdmin: func(r *http.Request) bool { _, ok := service.PublicAdmin(r); return ok }})
	h.Register(mux)
	RegisterManagement(mux, ManagementConfig{
		Service: managementService, Auth: service,
		PublicAdmin:        func(r *http.Request) bool { _, ok := service.PublicAdmin(r); return ok },
		ScheduledJobsToken: "fixture-scheduled-token", WorkerMode: true,
		DispatchMode: "service", ScheduledJobsReceiptLimit: 100000,
	})
	return mux, token
}

func legacyRequest(mux http.Handler, method, path, body, token, idempotency string, headers map[string]string) *httptest.ResponseRecorder {
	r := httptest.NewRequest(method, "https://news.fixture.test"+path, strings.NewReader(body))
	if body != "" {
		r.Header.Set("Content-Type", "application/json")
	}
	if token != "" {
		r.Header.Set("Authorization", "Bearer "+token)
	}
	if idempotency != "" {
		r.Header.Set("Idempotency-Key", idempotency)
	}
	for key, value := range headers {
		r.Header.Set(key, value)
	}
	w := httptest.NewRecorder()
	mux.ServeHTTP(w, r)
	return w
}

func TestLegacyWorkerModeCommandsReturnReceiptsAndPersistPythonPayloads(t *testing.T) {
	db := newLegacyContractDB(t)
	ctx := context.Background()
	if _, err := db.pool.Exec(ctx, `INSERT INTO sources(id,name,source_type,url,enabled) VALUES(7,'Disabled fixture','rss','https://fixture.test/rss',false)`); err != nil {
		t.Fatal(err)
	}
	if _, err := db.pool.Exec(ctx, `INSERT INTO articles(id,source_id,title,url,processing_state) VALUES(51,7,'Fixture 51','https://fixture.test/51','pending'),(52,7,'Fixture 52','https://fixture.test/52','completed')`); err != nil {
		t.Fatal(err)
	}
	mux, adminToken := legacyAdminHTTP(t, db)
	call := func(path, body, key string) string {
		t.Helper()
		w := legacyRequest(mux, http.MethodPost, path, body, adminToken, key, nil)
		if w.Code != http.StatusAccepted {
			t.Fatalf("POST %s status=%d body=%s", path, w.Code, w.Body.String())
		}
		var receipt struct {
			Success   bool   `json:"success"`
			Status    string `json:"status"`
			JobID     string `json:"job_id"`
			StatusURL string `json:"status_url"`
		}
		if err := json.Unmarshal(w.Body.Bytes(), &receipt); err != nil {
			t.Fatal(err)
		}
		if !receipt.Success || receipt.Status != "queued" || receipt.JobID == "" || receipt.StatusURL != "/api/v1/jobs/"+receipt.JobID {
			t.Fatalf("unexpected accepted receipt for %s: %#v", path, receipt)
		}
		return receipt.JobID
	}
	assertJob := func(id, kind string, expected map[string]any) {
		t.Helper()
		var gotKind string
		var raw []byte
		if err := db.pool.QueryRow(ctx, `SELECT kind,payload FROM background_jobs WHERE id=$1`, id).Scan(&gotKind, &raw); err != nil {
			t.Fatal(err)
		}
		var got map[string]any
		if err := json.Unmarshal(raw, &got); err != nil {
			t.Fatal(err)
		}
		if gotKind != kind || !reflect.DeepEqual(got, expected) {
			t.Fatalf("persisted command changed: kind=%s payload=%#v, want %s %#v", gotKind, got, kind, expected)
		}
	}

	sourceID := call("/api/v1/sources/7/test", "", "source-test-disabled")
	assertJob(sourceID, "source_test", map[string]any{"source_id": float64(7)})
	var enabled bool
	if err := db.pool.QueryRow(ctx, `SELECT enabled FROM sources WHERE id=7`).Scan(&enabled); err != nil || enabled {
		t.Fatalf("testing a disabled source changed its enabled state: enabled=%t err=%v", enabled, err)
	}
	var countBeforeMissing int
	if err := db.pool.QueryRow(ctx, `SELECT count(*) FROM background_jobs`).Scan(&countBeforeMissing); err != nil {
		t.Fatal(err)
	}
	missing := legacyRequest(mux, http.MethodPost, "/api/v1/sources/999/test", "", adminToken, "source-test-missing", nil)
	if missing.Code != http.StatusNotFound {
		t.Fatalf("missing source status=%d body=%s", missing.Code, missing.Body.String())
	}
	var countAfterMissing int
	if err := db.pool.QueryRow(ctx, `SELECT count(*) FROM background_jobs`).Scan(&countAfterMissing); err != nil || countAfterMissing != countBeforeMissing {
		t.Fatalf("missing source created a queue row: before=%d after=%d err=%v", countBeforeMissing, countAfterMissing, err)
	}

	defaultReprocess := call("/api/v1/articles/51/reprocess", `{}`, "article-defaults")
	assertJob(defaultReprocess, "article_reprocess", map[string]any{"article_ids": []any{float64(51)}, "force": true, "reextract_media": false})
	explicitReprocess := call("/api/v1/articles/52/reprocess", `{"force":false,"reextract_media":true}`, "article-explicit-options")
	assertJob(explicitReprocess, "article_reprocess", map[string]any{"article_ids": []any{float64(52)}, "force": false, "reextract_media": true})
	selectedRetry := call("/api/v1/process/retry", `{"article_ids":[12,13]}`, "selected-retry")
	assertJob(selectedRetry, "article_reprocess", map[string]any{"article_ids": []any{float64(12), float64(13)}, "force": false, "reextract_media": false})
	processing := call("/api/v1/process/run", `{}`, "manual-processing")
	assertJob(processing, "news_processing", map[string]any{})
}


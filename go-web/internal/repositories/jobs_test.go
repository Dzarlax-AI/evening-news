package repositories

import (
	"context"
	"errors"
	"fmt"
	"net"
	"os"
	"strings"
	"sync"
	"testing"
	"time"

	"github.com/Dzarlax-AI/evening-news/go-web/internal/jobs"
	"github.com/jackc/pgx/v5/pgxpool"
)

func TestPostgresJobAcceptanceAndOccurrenceReceipts(t *testing.T) {
	url := os.Getenv("TEST_DATABASE_URL")
	if url == "" {
		t.Skip("TEST_DATABASE_URL is required for isolated PostgreSQL job tests")
	}
	cfg, err := pgxpool.ParseConfig(url)
	if err != nil {
		t.Fatal(err)
	}
	ip := net.ParseIP(cfg.ConnConfig.Host)
	if cfg.ConnConfig.Host != "localhost" && (ip == nil || !ip.IsLoopback()) {
		t.Fatalf("TEST_DATABASE_URL must use loopback, got host %q", cfg.ConnConfig.Host)
	}
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	admin, err := pgxpool.NewWithConfig(ctx, cfg)
	if err != nil {
		t.Fatal(err)
	}
	defer admin.Close()
	schema := fmt.Sprintf("test_jobs_%d", time.Now().UnixNano())
	if _, err = admin.Exec(ctx, "CREATE SCHEMA "+schema); err != nil {
		t.Fatal(err)
	}
	defer admin.Exec(context.Background(), "DROP SCHEMA "+schema+" CASCADE")
	appCfg, err := pgxpool.ParseConfig(url)
	if err != nil {
		t.Fatal(err)
	}
	appCfg.ConnConfig.RuntimeParams["search_path"] = schema
	pool, err := pgxpool.NewWithConfig(ctx, appCfg)
	if err != nil {
		t.Fatal(err)
	}
	defer pool.Close()
	ddl := []string{
		`CREATE TABLE background_jobs(id uuid PRIMARY KEY, queue_position bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE NOT NULL, kind varchar(40) NOT NULL, payload jsonb NOT NULL, idempotency_key varchar(200) UNIQUE NOT NULL, coalesce_key varchar(64), state varchar(24) NOT NULL DEFAULT 'queued', created_at timestamp NOT NULL DEFAULT (timezone('UTC',now())), started_at timestamp, finished_at timestamp, owner_generation integer, attempt_generation integer NOT NULL DEFAULT 0, initialized_at timestamp, schedule_key varchar(128), schedule_revision integer, occurrence_id uuid, scheduled_for timestamp, result jsonb, error_code varchar(40))`,
		`CREATE UNIQUE INDEX idx_background_jobs_active_coalesce ON background_jobs(coalesce_key) WHERE state IN ('queued','running','interrupted') AND coalesce_key IS NOT NULL`,
		`CREATE TABLE background_job_idempotency_keys(key varchar(200) PRIMARY KEY,job_id uuid NOT NULL REFERENCES background_jobs(id) ON DELETE CASCADE,created_at timestamp NOT NULL DEFAULT (timezone('UTC',now())))`,
		`CREATE TABLE background_worker_status(id integer PRIMARY KEY,generation bigint NOT NULL DEFAULT 0,owner_id uuid,heartbeat_at timestamp,status varchar(16) NOT NULL DEFAULT 'stopped')`,
		`CREATE TABLE scheduler_occurrence_receipts(occurrence_id uuid PRIMARY KEY,envelope_sha256 varchar(64) NOT NULL,job_id uuid NOT NULL,accepted_at timestamp NOT NULL DEFAULT (timezone('UTC',now())))`,
		`INSERT INTO background_worker_status(id,generation,status,heartbeat_at) VALUES(1,3,'running',timezone('UTC',now()))`,
	}
	for _, q := range ddl {
		if _, err = pool.Exec(ctx, q); err != nil {
			t.Fatal(err)
		}
	}
	store := NewJobRepository(pool)
	svc := jobs.New(store)

	// Simultaneous identical producers serialize under the same advisory lock.
	command := jobs.SubmitCommand{Kind: "source_test", Payload: map[string]any{"source_id": 811}, IdempotencyKey: "web-submit-concurrent-1"}
	var wg sync.WaitGroup
	results := make([]jobs.SubmitResult, 2)
	errs := make([]error, 2)
	for i := range results {
		wg.Add(1)
		go func(i int) { defer wg.Done(); results[i], errs[i] = svc.Submit(ctx, command) }(i)
	}
	wg.Wait()
	for _, e := range errs {
		if e != nil {
			t.Fatal(e)
		}
	}
	if results[0].Job.ID != results[1].Job.ID || results[0].Created == results[1].Created {
		t.Fatalf("not idempotent: %#v %#v", results[0], results[1])
	}
	// Different request aliases coalesce only to matching active semantic work.
	alias := command
	alias.IdempotencyKey = "web-submit-alias-2"
	r, err := svc.Submit(ctx, alias)
	if err != nil {
		t.Fatal(err)
	}
	if r.Job.ID != results[0].Job.ID || r.Created {
		t.Fatalf("expected active coalesce, got %#v", r)
	}
	conflict := command
	conflict.Payload = map[string]any{"source_id": 812}
	if _, err = svc.Submit(ctx, conflict); !errors.Is(err, jobs.ErrIdempotencyConflict) {
		t.Fatalf("expected typed idempotency conflict, got %v", err)
	}
	wrongKind := jobs.SubmitCommand{Kind: "news_processing", Payload: map[string]any{}, IdempotencyKey: command.IdempotencyKey}
	if _, err = svc.Submit(ctx, wrongKind); !errors.Is(err, jobs.ErrIdempotencyConflict) {
		t.Fatalf("expected kind conflict, got %v", err)
	}
	readBack, err := svc.Get(ctx, results[0].Job.ID)
	if err != nil || !readBack.WorkerAvailable {
		t.Fatalf("expected healthy worker in job response: %#v %v", readBack, err)
	}

	occ := jobs.OccurrenceCommand{Version: 1, OccurrenceID: "00000000-0000-4000-8000-000000000001", IdempotencyKey: "00000000-0000-4000-8000-000000000001", ScheduleKey: "news.daily", ScheduleRevision: 4, ScheduledFor: "2026-10-26T10:00:00Z", Operation: "news_digest", Payload: map[string]any{"send_telegram": false}, WorkerMode: true, DispatchMode: "service", ReceiptLimit: 100000}
	first, err := svc.AcceptOccurrence(ctx, occ)
	if err != nil {
		t.Fatal(err)
	}
	if !first.Created || first.JobID == "" {
		t.Fatalf("expected created occurrence: %#v", first)
	}
	second, err := svc.AcceptOccurrence(ctx, occ)
	if err != nil {
		t.Fatal(err)
	}
	if second.Created || second.JobID != first.JobID {
		t.Fatalf("expected exact duplicate receipt: %#v", second)
	}
	if _, err = pool.Exec(ctx, `UPDATE background_worker_status SET status='stopped',heartbeat_at=NULL WHERE id=1`); err != nil {
		t.Fatal(err)
	}
	second, err = svc.AcceptOccurrence(ctx, occ)
	if err != nil || second.Created {
		t.Fatalf("duplicate receipt must bypass current worker readiness: %#v %v", second, err)
	}
	changed := occ
	changed.ScheduleRevision++
	if _, err = svc.AcceptOccurrence(ctx, changed); !errors.Is(err, jobs.ErrIdempotencyConflict) {
		t.Fatalf("expected envelope conflict, got %v", err)
	}
	missing, err := svc.Get(ctx, "00000000-0000-4000-8000-000000000099")
	if !errors.Is(err, jobs.ErrNotFound) {
		t.Fatalf("expected not found, got %#v %v", missing, err)
	}
	status, err := svc.Status(ctx)
	if err != nil || status.Healthy {
		t.Fatalf("expected stopped worker status: %#v %v", status, err)
	}
	if len(first.JobID) != 36 || strings.Count(first.JobID, "-") != 4 {
		t.Fatalf("expected UUID id, got %q", first.JobID)
	}
}
